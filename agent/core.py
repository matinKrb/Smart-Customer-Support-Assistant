AVAILABLE_FUNCTIONS = {
    "get_order_status":business_api.get_order_status,
    "search_product":business_api.search_product,
    "create_support_ticket":business_api.create_support_ticket,
    "request_human_handoff":business_api.request_human_handoff,
    "search_knowledge": search_knowledge
}

def run_agent(conversation , user_message : str)->str:
    last_messages =conversation.messages.order_by('-created_at')[:10]
    last_messages = list(reversed(last_messages))

    history =[]
    for message in last_messages:
        if message.sender == 'customer':
            role = 'user'
        elif message.sender == 'ai':
            role = 'assistant'
        else:
            continue
        history.append({"role": role, "content": message.text})

    messages = [{"role": "system", "content": SYSTEM_PROMPT}] + history + [{"role": "user", "content": user_message}]

    while True:
        response = client.chat.completions.create(
            model=MODEL_NAME,
            messages=messages ,
            tools=TOOLS_SCHEMA
        )
        response_message = response.choices[0].message
        if not response_message.tool_calls:
            return response_message.content

        messages.append(response_message)

        for tool_call in response_message.tool_calls:
            function_name = tool_call.function.name
            print(f"MODEL CALLED TOOL: {function_name}")

            function_args = json.loads(tool_call.function.arguments)

            if function_name == "request_human_handoff":
                function_args["conversation_id"] = str(conversation.uuid)

            function_to_call = AVAILABLE_FUNCTIONS.get(function_name)
            function_result = function_to_call(**function_args)

            messages.append({
                "role": "tool",
                "tool_call_id": tool_call.id,
                "content": json.dumps(function_result),
            })


            if function_name == "search_knowledge":
                messages.append({
                    "role": "system",
                    "content": "پاسخ نهایی خود را دقیقاً بر اساس محتوای بازگشتی بالا بده، بدون افزودن یا تغییر دادن اطلاعات."
                })